# -*- coding: utf-8 -*-
"""
What If Lab · 距离即权限 —— 设备端全局配置

引脚编号必须以自己的板子丝印为准后再上电。这里的默认值来自
QuecDuino 传感器套件官方示例，但官方示例之间本身存在引脚冲突
（超声波 Echo 与蜂鸣器都默认 GPIO31），所以本项目重新做了分配，
理由写在 PIN 表下方。
"""

DEVICE_ID = "whatif-prox-01"

# ---------------------------------------------------------------------------
# 引脚分配
# ---------------------------------------------------------------------------
# 冲突记录（这是本项目必须重排引脚的唯一原因）：
#   官方 ultrasonic_gpio.py  默认 echo_pin = Pin.GPIO31
#   官方 Buzzer.py           默认 pin      = Pin.GPIO31
#   官方 Display_LCD.py      b 段          = Pin.GPIO31
#   官方 rgb_led.py 示例      green         = Pin.GPIO31
# 三者任取其二就会同时接上而不报错，现象是"距离读数乱跳"或"蜂鸣器自己响"，
# 极难往引脚冲突上想。本项目把 GPIO31 独占给 Echo，其余全部让开。
#
# 数码管（JY005）要占 8 个 GPIO，和上面的分配表打架，MVP 不接。
PIN = {
    "trig":  30,    # HC-SR04 Trig（板子输出 3.3V，模块认 >2V 即高，无需电平转换）
    "echo":  31,    # HC-SR04 Echo —— 必须经 1k/2k 分压后进板，见 docs/接线.md
    "rgb_r": 32,
    "rgb_g": 4,
    "rgb_b": 5,
    "buzzer": 6,    # 套件蜂鸣器是低电平触发
    "led":    7,    # 单 LED，做"正在听"的心跳指示
    "lux":   None,  # KY-018 走 ADC，见 ADC_CHANNEL
}

ADC_CHANNEL = "ADC1"      # KY-018 光敏；必须分压，ADC 量程只有 0-1.2V
LUX_DIVIDER = (10.0, 2.7)  # (R1 kΩ, R2 kΩ)，Vout = Vin × R2/(R1+R2)

# ---------------------------------------------------------------------------
# 距离分档（单位 cm）
# ---------------------------------------------------------------------------
# 为什么用「进入线 / 离开线」两条线而不是一个阈值：
# 超声换能器在边界附近有 ±2~3cm 抖动，单阈值会让档位疯狂跳变，
# 表现是屏幕上的文字一闪一闪。两条线之间的死区就是用来吃掉这个抖动的。
TIER2_ENTER_CM = 38.0   # 凑到这个距离，AI 说完整的话
TIER2_LEAVE_CM = 52.0   # 退到这里才算离开
TIER1_ENTER_CM = 95.0   # 中距离，AI 只给一句
TIER1_LEAVE_CM = 115.0  # 再远就是 0 档

# 档位编号与 proximity.ProximityJudge 对齐，main 里用它做条件判断，
# 避免到处写魔法数字 0/1/2。
TIER_OUTSIDE = 0
TIER_MID = 1
TIER_CLOSE = 2

# 升档要连续确认帧，降档一帧就切。
# 升档慢是为了防抖；降档快是刻意设计的——观众一退开文字立刻断，
# 这个"被切断"的瞬间是整个 demo 最好笑的时刻，也是观众会自己反复凑近的原因。
RAISE_CONFIRM_FRAMES = 4
LOWER_CONFIRM_FRAMES = 1
NO_ECHO_TIMEOUT_MS = 600   # 连续这么多毫秒读不到回波，视为无人，直接 0 档

SAMPLE_INTERVAL_MS = 100   # 测距节拍；单次测量最坏耗时约 26ms，不会压帧

# ---------------------------------------------------------------------------
# 访客会话
# ---------------------------------------------------------------------------
SESSION_GAP_MS = 1500   # 回到 0 档超过这个时间才算上一次访问结束
                         # 否则一次抖动会被拆成两条访问记录，统计失真

# ---------------------------------------------------------------------------
# 上报
# ---------------------------------------------------------------------------
REPORT_INTERVAL_MS = 400   # 状态上报节拍，Cat.1bis 上行 5Mbps，这个频率毫无压力

MQTT_HOST = ""        # 必填：公网 broker 域名或 IP
MQTT_PORT = 1883
MQTT_USER = ""
MQTT_PASSWORD = ""
TOPIC_STATE = "/whatif/{}/state".format(DEVICE_ID)   # 上行：档位 + 传感量
TOPIC_CMD = "/whatif/{}/cmd".format(DEVICE_ID)       # 下行：调阈值、切话题

# 云端答案服务。走公网 IP 或域名，不能填 192.168.x.x ——
# 板子在运营商 NAT 后，内网地址解析到也连不上。
API_BASE = ""         # 必填：例如 http://<公网IP>:8000

# ---------------------------------------------------------------------------
# 话题：AI 在琢磨什么
# ---------------------------------------------------------------------------
# 设备只带一个 topic 编号，内容由云端生成。路演时可以现场切换，
# 让同一个硬件对不同的东西"发表意见"。
TOPICS = {
    1: "这个展位现场的人群行为",
    2: "这间屋子里的空气与光线适不适合人待着",
    3: "凑近我的这些人的性格",
}
TOPIC_ID = 1

# ---------------------------------------------------------------------------
# 本地缓存
# ---------------------------------------------------------------------------
CACHE_PATH = "/usr/answer.json"    # 用户文件系统只在 /usr 下可写
CACHE_KEEP = 6                      # 保留最近 6 份三档文案
